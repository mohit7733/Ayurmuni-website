export const bookingStatusLabel = (status) => {
  const key = String(status || '').toUpperCase();
  const labels = {
    CONFIRMED: 'Confirmed',
    BOOKED: 'Booked',
    COMPLETED: 'Completed',
    CANCELLED: 'Cancelled',
    UPCOMING: 'Upcoming',
    PENDING: 'Pending',
  };
  return labels[key] || (key ? key.replace(/_/g, ' ') : 'Confirmed');
};
